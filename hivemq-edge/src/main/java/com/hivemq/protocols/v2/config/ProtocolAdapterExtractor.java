package com.hivemq.protocols.v2.config;

import com.hivemq.configuration.entity.HiveMQConfigEntity;
import com.hivemq.configuration.reader.Configurator;
import com.hivemq.configuration.reader.ReloadableExtractor;
import jakarta.xml.bind.ValidationEvent;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.Set;
import java.util.function.Consumer;
import java.util.stream.Collectors;
import org.jetbrains.annotations.NotNull;
import org.jetbrains.annotations.Nullable;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

/**
 * Reads the {@code <v2>} configuration section, mirroring the legacy
 * {@link com.hivemq.configuration.reader.ProtocolAdapterExtractor} consumer-callback pattern (parse on read, validate,
 * notify a registered consumer) but <b>read-only</b>: Edge never writes this section — it is generated by external
 * tooling. The registered consumer {@code tell}s a {@code ConfigurationChanged} to the
 * Protocol Adapter Manager mailbox; this is the same path at startup and on every reload.
 * <p>
 * Validation failures — duplicate tag names, mapping references that do not resolve to a declared tag, an invalid
 * {@code protocol-id} or topic, the watchdog/command-timeout invariant (S32), or two adapters sharing an
 * {@code adapter-id} — are <b>scoped to the single adapter they belong to</b>; a bad adapter never rejects the
 * section and never takes the node down (EDG-824 #4). Per adapter:
 * <ul>
 * <li>an invalid replacement for a previously-accepted adapter keeps the previously-applied configuration running
 * untouched (transactional per-adapter rejection);</li>
 * <li>an invalid <b>new</b> adapter is reported in the update's
 * {@link ProtocolAdapterConfigUpdate#rejected() rejected} list, which the manager surfaces as an {@code ERROR}
 * adapter visible via REST;</li>
 * <li>a duplicate {@code adapter-id} makes the document structurally ambiguous, so <b>neither</b> declaration is
 * applied and the outcome never depends on their order or validity (EDG-824 #4, Sam #4): an already-running adapter
 * keeps its previously-applied configuration (last-known-good), and a new id is surfaced as a single rejected
 * {@code ERROR} adapter — reordering the duplicates can never change which adapter is live;</li>
 * <li>an entry without an {@code adapter-id} cannot be addressed at all and is dropped with an error log.</li>
 * </ul>
 */
public class ProtocolAdapterExtractor
        implements ReloadableExtractor<List<@NotNull ProtocolAdapterEntity>, ProtocolAdapterConfigUpdate> {

    private static final @NotNull Logger log = LoggerFactory.getLogger(ProtocolAdapterExtractor.class);

    private volatile @NotNull List<ProtocolAdapterEntity> allConfigs = List.of();
    private volatile @NotNull List<RejectedAdapterEntity> rejectedConfigs = List.of();
    /** The section verbatim as last parsed — what {@link #sync} re-emits, never the derived/filtered view. */
    private volatile @NotNull List<ProtocolAdapterEntity> lastParsedSection = List.of();

    private volatile @Nullable Consumer<ProtocolAdapterConfigUpdate> consumer =
            configs -> log.debug("No v2 protocol adapter consumer registered yet");

    public @NotNull List<ProtocolAdapterEntity> getAllConfigs() {
        return allConfigs;
    }

    public @NotNull Optional<ProtocolAdapterEntity> getAdapterByAdapterId(final @NotNull String adapterId) {
        return allConfigs.stream()
                .filter(adapter -> adapter.getAdapterId().equals(adapterId))
                .findFirst();
    }

    @Override
    public synchronized @NotNull Configurator.ConfigResult updateConfig(final @NotNull HiveMQConfigEntity config) {
        lastParsedSection = List.copyOf(config.getV2().getProtocolAdapters());
        final Map<String, ProtocolAdapterEntity> previousById =
                allConfigs.stream().collect(Collectors.toMap(ProtocolAdapterEntity::getAdapterId, entity -> entity));

        // A non-empty adapter-id that appears more than once makes the document structurally ambiguous: there is no
        // deterministic, order-independent way to pick which declaration is live. Count occurrences up front so the
        // outcome for a duplicate id depends only on the SET of declarations — never on their order or their validity.
        // Empty adapter-ids are excluded here: they cannot be addressed, so they are never treated as duplicates and
        // fall through to the normal per-entry validation below, where each is dropped with an error log.
        final Map<String, Long> occurrencesById = lastParsedSection.stream()
                .map(ProtocolAdapterEntity::getAdapterId)
                .filter(adapterId -> !adapterId.isEmpty())
                .collect(Collectors.groupingBy(adapterId -> adapterId, Collectors.counting()));

        final List<ProtocolAdapterEntity> accepted = new ArrayList<>();
        final List<RejectedAdapterEntity> rejected = new ArrayList<>();
        final Set<String> ambiguousIdsResolved = new HashSet<>();

        for (final ProtocolAdapterEntity entity : lastParsedSection) {
            final String adapterId = entity.getAdapterId();

            if (!adapterId.isEmpty() && occurrencesById.getOrDefault(adapterId, 0L) > 1) {
                // Ambiguous duplicate: apply NEITHER declaration. Resolve the id exactly once, regardless of how many
                // times or in which order the duplicates appear.
                if (ambiguousIdsResolved.add(adapterId)) {
                    if (previousById.containsKey(adapterId)) {
                        // Already running: keep the last-known-good configuration untouched.
                        log.error(
                                "v2 protocol adapter config error: adapter-id [{}] is declared more than once; "
                                        + "the document is ambiguous — keeping the previously applied configuration "
                                        + "and applying neither declaration",
                                adapterId);
                        accepted.add(previousById.get(adapterId));
                    } else {
                        // New id: surface exactly one ERROR adapter; neither declaration is applied.
                        log.error(
                                "v2 protocol adapter config error: adapter-id [{}] is declared more than once; "
                                        + "the document is ambiguous — rejecting the adapter and applying neither "
                                        + "declaration",
                                adapterId);
                        rejected.add(new RejectedAdapterEntity(
                                entity,
                                "duplicate adapter-id '"
                                        + adapterId
                                        + "': the document declares this adapter-id more than once, which is "
                                        + "ambiguous; neither declaration was applied"));
                    }
                }
                continue;
            }

            final List<ValidationEvent> validationEvents = new ArrayList<>();
            entity.validate(validationEvents);
            validationEvents.stream()
                    .filter(event -> event.getSeverity() == ValidationEvent.WARNING)
                    .forEach(event -> log.warn("v2 protocol adapter config warning: {}", event.getMessage()));
            final List<String> errors = validationEvents.stream()
                    .filter(event -> event.getSeverity() == ValidationEvent.FATAL_ERROR
                            || event.getSeverity() == ValidationEvent.ERROR)
                    .map(ValidationEvent::getMessage)
                    .toList();
            if (errors.isEmpty()) {
                accepted.add(entity);
                continue;
            }

            errors.forEach(message -> log.error("v2 protocol adapter config error: {}", message));
            if (adapterId.isEmpty()) {
                // Nothing addressable to keep or surface; the entry is dropped, the section is still applied.
                log.error("v2 protocol adapter config error: an adapter entry without an adapter-id was dropped");
            } else if (previousById.containsKey(adapterId)) {
                // Transactional per-adapter rejection: the running adapter keeps its previously-applied
                // configuration; the invalid replacement never disrupts it.
                log.error(
                        "The replacement configuration of v2 adapter '{}' is invalid; "
                                + "keeping the previously applied configuration",
                        adapterId);
                accepted.add(previousById.get(adapterId));
            } else {
                rejected.add(new RejectedAdapterEntity(entity, String.join("; ", errors)));
            }
        }

        allConfigs = List.copyOf(accepted);
        rejectedConfigs = List.copyOf(rejected);
        notifyConsumer();
        return Configurator.ConfigResult.SUCCESS;
    }

    private void notifyConsumer() {
        final Consumer<ProtocolAdapterConfigUpdate> currentConsumer = this.consumer;
        if (currentConsumer != null) {
            currentConsumer.accept(new ProtocolAdapterConfigUpdate(allConfigs, rejectedConfigs));
        }
    }

    @Override
    public synchronized void registerConsumer(final @NotNull Consumer<ProtocolAdapterConfigUpdate> consumer) {
        this.consumer = consumer;
        notifyConsumer();
    }

    @Override
    public boolean needsRestartWithConfig(final @NotNull HiveMQConfigEntity config) {
        return false;
    }

    @Override
    public synchronized void sync(final @NotNull HiveMQConfigEntity entity) {
        // Round-trip what was PARSED so a disk write triggered by another subsystem preserves the section verbatim.
        // Edge never modifies the v2 section. Emitting the derived/accepted view instead would silently revert a
        // user's invalid-but-present edit (kept-previous substitution) or delete a rejected entry from disk.
        entity.getV2().getProtocolAdapters().clear();
        entity.getV2().getProtocolAdapters().addAll(lastParsedSection);
    }
}
